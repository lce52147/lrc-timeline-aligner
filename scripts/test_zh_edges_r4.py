def tsv_rows():
    yield "id\tsimplified\texpected\tprobe\tnote"
    for number, (word, side, text, want) in enumerate(ATTACKS, 1):
        yield "E%03d\t%s\t%s\t%s\tedge %s of %s" % (number, text, want, word, side, word)


class EdgeAttackTests(unittest.TestCase):
    def test_every_attack(self) -> None:
        bad = []
        for word, side, text, want in ATTACKS:
            got = zh_traditional.convert_text(text)
            if got != want:
                bad.append((word, side, text, want, got))
        self.assertEqual(bad, [])

    def test_every_non_preference_word_has_three_attacks_on_each_side(self) -> None:
        for entry in zh_traditional.CORRECTIONS:
            for side in "LR":
                count = sum(1 for word, s, _t, _w in ATTACKS if s == side and entry.key.startswith(word[:len(entry.key)]) and word.startswith(entry.key[:len(word)]))
                self.assertGreaterEqual(count, 3, (entry.key, side))

    def test_every_attack_extends_its_word(self) -> None:
        for word, side, text, _want in ATTACKS:
            self.assertIn(word, text, (word, text))
            self.assertNotEqual(text.startswith(word) and text.endswith(word), True, (word, text))


